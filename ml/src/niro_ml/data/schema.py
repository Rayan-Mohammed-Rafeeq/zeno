# Data quality record
# ---------------------------------------------------------------------------

class DataQualityStats(BaseModel):
    """
    Summary statistics produced by the data quality pipeline for every
    dataset run.  Stored alongside the feature data for auditability.
    Never silently discard rejected records — track them here.
    """

    rows_received: int = 0
    rows_accepted: int = 0
    rows_rejected: int = 0
    duplicate_rows: int = 0
    missing_transaction_id: int = 0
    missing_customer_id: int = 0
    missing_merchant_id: int = 0
    missing_timestamp: int = 0
    invalid_timestamp: int = 0
    future_timestamp: int = 0
    missing_amount: int = 0
    invalid_amount: int = 0       # zero, negative, or non-numeric
    amount_extreme_high: int = 0  # above configurable ceiling (default $1M)
    missing_currency: int = 0
    invalid_currency: int = 0
    rejection_reasons: list[str] = Field(default_factory=list)

    @property
    def acceptance_rate(self) -> float:
        if self.rows_received == 0:
            return 0.0
        return self.rows_accepted / self.rows_received

    @property
    def rejection_rate(self) -> float:
        return 1.0 - self.acceptance_rate

    def summary(self) -> dict:
        return {
            "rows_received":     self.rows_received,
            "rows_accepted":     self.rows_accepted,
            "rows_rejected":     self.rows_rejected,
            "acceptance_rate":   round(self.acceptance_rate, 4),
            "duplicate_rows":    self.duplicate_rows,
            "missing_critical":  (
                self.missing_transaction_id
                + self.missing_customer_id
                + self.missing_merchant_id
                + self.missing_timestamp
                + self.missing_amount
            ),
            "invalid_amounts":   self.invalid_amount,
            "invalid_timestamps": self.invalid_timestamp + self.future_timestamp,
        }
